import AppKit
import Observation
import Darwin

struct ClipboardEntry: Codable, Identifiable, Equatable {
    var id = UUID()
    var text: String
    var date: Date
    var sourceID: String
    var sourceName: String
    var favorite = false
    var rtf: Data? = nil
    var isLink: Bool {
        guard text.rangeOfCharacter(from: .whitespacesAndNewlines) == nil,
              let url = URL(string: text), ["https", "http"].contains(url.scheme?.lowercased() ?? "") else { return false }
        return url.host?.isEmpty == false
    }
    var matches: String { text + "\n" + sourceName }
}

enum ClipboardPolicy {
    static let maximumTextBytes = 16_384
    static let maximumRTFBytes = 16_384
    static let maximumFileBytes = 8_000_000
    static let maximumFavorites = 50
    static let protectedApps: Set<String> = ["com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx", "com.bitwarden.desktop", "com.dashlane.Dashlane", "org.keepassxc.keepassxc", "com.apple.Passwords"]
    static let ignoredTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type", NSPasteboard.PasteboardType.fileURL.rawValue]
    static func accepts(types: Set<String>, sources: [String], excluded: [String]) -> Bool {
        ignoredTypes.isDisjoint(with: types) && Set(sources).isDisjoint(with: protectedApps.union(excluded))
    }
    static func validText(_ text: String) -> Bool {
        !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && text.utf8.count <= maximumTextBytes
    }
    static func adding(_ text: String, date: Date, sourceID: String, sourceName: String, to entries: [ClipboardEntry], limit: Int, rtf: Data? = nil) -> [ClipboardEntry] {
        guard validText(text) else { return entries }
        var next = entries
        var entry = next.first { $0.text == text } ?? ClipboardEntry(text: text, date: date, sourceID: sourceID, sourceName: sourceName)
        next.removeAll { $0.text == text }
        entry.date = date; entry.sourceID = String(sourceID.prefix(255)); entry.sourceName = String(sourceName.prefix(80))
        entry.rtf = rtf.flatMap { $0.count <= maximumRTFBytes ? $0 : nil }
        next.insert(entry, at: 0)
        return trimmed(next, limit: limit)
    }
    static func trimmed(_ entries: [ClipboardEntry], limit: Int) -> [ClipboardEntry] {
        var recent = 0
        var next = entries.filter { entry in
            if entry.favorite { return true }
            recent += 1; return recent <= min(500, max(10, limit))
        }
        // Count the encoded size too: escaped text can be much larger than UTF-8.
        while (try? JSONEncoder().encode(ClipboardArchive(entries: next)).count) ?? Int.max > maximumFileBytes,
              let index = next.lastIndex(where: { !$0.favorite }) { next.remove(at: index) }
        return next
    }
}

struct ClipboardArchive: Codable {
    var version = 1
    var entries: [ClipboardEntry]
    func validated() throws -> [ClipboardEntry] {
        guard version == 1, entries.count <= 550, Set(entries.map(\.id)).count == entries.count,
              Set(entries.map(\.text)).count == entries.count,
              entries.filter(\.favorite).count <= ClipboardPolicy.maximumFavorites,
              entries.allSatisfy({ ClipboardPolicy.validText($0.text) && $0.sourceID.count <= 255 && $0.sourceName.count <= 80 && ($0.rtf?.count ?? 0) <= ClipboardPolicy.maximumRTFBytes && $0.date.timeIntervalSince1970.isFinite }) else {
            throw SettingsError.invalid("La cronologia clipboard non è leggibile. Non è stata sovrascritta; puoi cancellarla dalle impostazioni.")
        }
        return entries.sorted { $0.date > $1.date }
    }
}

enum ClipboardStorage {
    static func load(_ url: URL) throws -> [ClipboardEntry] {
        guard FileManager.default.fileExists(atPath: url.path) else { return [] }
        let size = try FileManager.default.attributesOfItem(atPath: url.path)[.size] as? NSNumber
        guard let size, size.intValue <= ClipboardPolicy.maximumFileBytes else { throw SettingsError.invalid("La cronologia clipboard è troppo grande.") }
        let handle = try FileHandle(forReadingFrom: url)
        defer { try? handle.close() }
        let data = try handle.read(upToCount: ClipboardPolicy.maximumFileBytes + 1) ?? Data()
        guard data.count <= ClipboardPolicy.maximumFileBytes else { throw SettingsError.invalid("La cronologia clipboard è troppo grande.") }
        return try JSONDecoder().decode(ClipboardArchive.self, from: data).validated()
    }
    static func save(_ entries: [ClipboardEntry], to url: URL) throws {
        let archive = ClipboardArchive(entries: entries)
        _ = try archive.validated()
        let data = try JSONEncoder().encode(archive)
        guard data.count <= ClipboardPolicy.maximumFileBytes else { throw SettingsError.invalid("La cronologia clipboard è troppo grande.") }
        let fm = FileManager.default
        try fm.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try fm.setAttributes([.posixPermissions: 0o700], ofItemAtPath: url.deletingLastPathComponent().path)
        let temporary = url.deletingLastPathComponent().appending(path: ".history-\(UUID().uuidString).tmp")
        defer { try? fm.removeItem(at: temporary) }
        try data.write(to: temporary, options: .withoutOverwriting)
        try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: temporary.path)
        guard Darwin.rename(temporary.path, url.path) == 0 else { throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno)) }
    }
}

@MainActor @Observable final class ClipboardStore {
    static var fileURL: URL { Model.preferencesURL.deletingLastPathComponent().appending(path: "clipboard/history.json") }
    private(set) var entries: [ClipboardEntry] = []
    private(set) var enabled = false
    private(set) var paused = false
    private(set) var accessDenied = false
    var error: String?
    var shortcutError: String?
    @ObservationIgnored private let url: URL?
    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private var lastChange = 0
    @ObservationIgnored private var limit = 100
    @ObservationIgnored private var exclusions: [String] = []
    @ObservationIgnored private var blocked = false

    init(url: URL? = nil, pasteboard: NSPasteboard = .general) {
        self.url = url; self.pasteboard = pasteboard
        if let url {
            do { entries = try ClipboardStorage.load(url) }
            catch { blocked = true; self.error = "La cronologia clipboard non è leggibile. Non è stata sovrascritta; puoi cancellarla dalle impostazioni." }
        }
    }
    func configure(enabled: Bool, paused: Bool, limit: Int, exclusions: [String]) {
        if self.enabled != enabled || self.paused != paused || self.exclusions != exclusions {
            lastChange = pasteboard.changeCount; accessDenied = false
        }
        self.enabled = enabled; self.paused = paused; self.exclusions = exclusions
        self.limit = min(500, max(10, limit))
        let trimmed = ClipboardPolicy.trimmed(entries, limit: self.limit)
        if trimmed != entries { commit(trimmed) }
    }
    func sample() {
        guard enabled, !paused, !blocked else { return }
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny { accessDenied = true; return }
        let front = pasteboard.name == .general ? NSWorkspace.shared.frontmostApplication : nil
        let source = pasteboard.string(forType: .init("org.nspasteboard.source")) ?? front?.bundleIdentifier ?? ""
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard ClipboardPolicy.accepts(types: types, sources: [source, front?.bundleIdentifier ?? ""], excluded: exclusions),
              let text = pasteboard.string(forType: .string), ClipboardPolicy.validText(text), pasteboard.changeCount == change else { return }
        let rtf = types.contains(NSPasteboard.PasteboardType.rtf.rawValue) ? pasteboard.data(forType: .rtf) : nil
        guard pasteboard.changeCount == change else { return }
        accessDenied = false
        let sourceName = source == front?.bundleIdentifier ? (front?.localizedName ?? source) : source
        commit(ClipboardPolicy.adding(text, date: Date(), sourceID: source, sourceName: sourceName, to: entries, limit: limit, rtf: rtf))
    }
    private func commit(_ next: [ClipboardEntry]) {
        guard !blocked else { return }
        do {
            if let url { try ClipboardStorage.save(next, to: url) }
            entries = next; error = nil
        } catch { self.error = "Impossibile salvare la cronologia clipboard. I dati precedenti sono stati conservati." }
    }
    func toggleFavorite(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        var next = entries
        if !next[index].favorite && next.filter(\.favorite).count >= ClipboardPolicy.maximumFavorites {
            error = "Puoi conservare al massimo 50 preferiti clipboard."; return
        }
        next[index].favorite.toggle()
        commit(ClipboardPolicy.trimmed(next, limit: limit))
    }
    func remove(_ id: UUID) { commit(entries.filter { $0.id != id }) }
    func clear(includingFavorites: Bool) {
        if blocked && !includingFavorites { error = "Archivio danneggiato: scegli Elimina tutto per ripartire."; return }
        let next = includingFavorites ? [] : entries.filter(\.favorite)
        do {
            if let url { try ClipboardStorage.save(next, to: url) }
            blocked = false; entries = next; error = nil; lastChange = pasteboard.changeCount
        } catch { self.error = "Impossibile cancellare la cronologia clipboard." }
    }
    func copy(_ entry: ClipboardEntry, plainText: Bool = false) -> Bool {
        let item = NSPasteboardItem()
        item.setString(entry.text, forType: .string)
        if !plainText, let rtf = entry.rtf { item.setData(rtf, forType: .rtf) }
        item.setString(Bundle.main.bundleIdentifier ?? "Sorayura", forType: .init("org.nspasteboard.source"))
        pasteboard.clearContents()
        let success = pasteboard.writeObjects([item])
        lastChange = pasteboard.changeCount
        if !success { error = "Impossibile copiare negli appunti." }
        return success
    }
}
